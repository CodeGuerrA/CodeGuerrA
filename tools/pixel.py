def glyph(ch):
    """Devolve a glifa com 10 linhas: 2 de acento, 7 da letra, 1 de descendente."""
    if ch == ",":
        return ["."] * 2 + _GLYPHS[","] + ["#"]
    if ch in _LOWER:
        body, desc = _LOWER[ch]
        blank = "." * len(body[0])
        return [blank, blank] + body + [desc]
    if ch in _LOWER_ACCENTED:
        base, accent = _LOWER_ACCENTED[ch]
        body, desc = _LOWER[base]
        return ["....."] * 2 + _LOWER_ACCENTS[accent] + body[2:] + [desc]
    if ch == "í":
        body, desc = _LOWER["i"]
        return ["..."] * 2 + ["..#", ".#."] + body[2:] + [desc]
    if ch == "ç":
        body, _ = _LOWER["c"]
        return ["....."] * 2 + body + ["..#.."]
    if ch in _EXTRA:
        body = _EXTRA[ch]
        blank = "." * len(body[0])
        return [blank, blank] + body + [blank]
    if ch == "Ç":
        body = _GLYPHS["C"]
        return ["....."] * 2 + body + ["..#.."]
    if ch in _ACCENTED:
        base, accent = _ACCENTED[ch]
        return _ACCENTS[accent] + _GLYPHS[base] + ["....."]
    body = _GLYPHS[ch]
    blank = "." * len(body[0])
    return [blank, blank] + body + [blank]


def text_width(text, cell):
    return sum((len(glyph(c)[0]) + 1) * cell for c in text) - cell


def text_rects(text, x, y, cell, color):
    """Texto bitmap. y é o topo da linha de acento; a letra começa em y + 2 células."""
    out = []
    cursor = x
    for ch in text:
        rows = glyph(ch)
        out += _runs(rows, cursor, y, cell, lambda c: color if c == "#" else None)
        cursor += (len(rows[0]) + 1) * cell
    return out


def sprite_rects(rows, x, y, cell, palette=PALETTE):
    width = max(len(r) for r in rows)
    rows = [r.ljust(width, ".") for r in rows]
    return _runs(rows, x, y, cell, lambda c: palette.get(c))


def _runs(rows, x, y, cell, color_of):
    out = []
    for j, row in enumerate(rows):
        i = 0
        while i < len(row):
            color = color_of(row[i])
            if color is None:
                i += 1
                continue
            start = i
            while i < len(row) and color_of(row[i]) == color:
                i += 1
            out.append(f'<rect x="{x + start * cell}" y="{y + j * cell}" width="{(i - start) * cell}" height="{cell}" fill="{color}"/>')
    return out


def wrap(text, max_width, cell):
    """Quebra o texto em linhas que cabem em max_width, palavra por palavra."""
    lines, current = [], ""
    for word in text.split():
        candidate = f"{current} {word}".strip()
        if current and text_width(candidate, cell) > max_width:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)
    return lines
